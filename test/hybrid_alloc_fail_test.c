#ifndef HYBRID_PROVIDER_SOURCES
# error "HYBRID_PROVIDER_SOURCES (the provider's source basenames) is set by CMake"
#endif

#define PROPQ HYBRID_TEST_PROPQ

/* Scenario outcomes. */
enum { RUN_UNSOUND = -1, RUN_FAILED = 0, RUN_OK = 1 };

static int tests, passed, failed, skipped;
static const unsigned char msg[] = "hybrid-provider allocation-failure message";

/* --- allocation hooks --- */

/*
 * Every block carries a header recording whether a provider site allocated it,
 * so frees (which may happen in libcrypto, e.g. for buffers the provider hands
 * out) are attributed correctly. The header is max_align_t-sized so the
 * returned pointer keeps malloc's alignment.
 */
typedef union {
    int provider;
    max_align_t align;
} BLOCK_HDR;

static long prov_allocs;     /* provider allocation sites reached so far */
static long fail_at = -1;    /* index of the provider allocation to fail */
static int injected;         /* the armed failure fired */
static long prov_live;       /* provider blocks currently allocated */

static int is_provider_site(const char *file)
{
    static const char list[] = HYBRID_PROVIDER_SOURCES;
    const char *base, *p;
    size_t n;

    if (file == NULL || *file == '\0')
        return 0;
    base = strrchr(file, '/');
    base = base != NULL ? base + 1 : file;
    n = strlen(base);
    for (p = list; (p = strstr(p, base)) != NULL; p += n)
        if ((p == list || p[-1] == ':') && (p[n] == ':' || p[n] == '\0'))
            return 1;
    return 0;
}

/* Call sites of a recording run's provider allocations, by index. */
#define MAX_RECORDED 8192
static int recording;
static const char *rec_file[MAX_RECORDED];
static int rec_line[MAX_RECORDED];
static unsigned char selected[MAX_RECORDED];
static const char *inj_file;
static int inj_line;

/* 1 iff this allocation is the provider-site one to fail; *prov receives
 * whether the site is the provider's. */
static int should_fail(const char *file, int line, int *prov)
{
    if (!(*prov = is_provider_site(file)))
        return 0;
    if (recording && prov_allocs < MAX_RECORDED) {
        rec_file[prov_allocs] = file;
        rec_line[prov_allocs] = line;
    }
    if (prov_allocs++ == fail_at) {
        injected = 1;
        inj_file = file;
        inj_line = line;
        return 1;
    }
    return 0;
}

static void *t_malloc(size_t num, const char *file, int line)
{
    BLOCK_HDR *b;
    int prov;

    if (should_fail(file, line, &prov)
            || (b = malloc(sizeof(*b) + num)) == NULL)
        return NULL;
    b->provider = prov;
    prov_live += prov;
    return b + 1;
}

static void t_free(void *ptr, const char *file, int line)
{
    BLOCK_HDR *b;

    (void)file; (void)line;
    if (ptr == NULL)
        return;
    b = (BLOCK_HDR *)ptr - 1;
    prov_live -= b->provider;
    free(b);
}

static void *t_realloc(void *ptr, size_t num, const char *file, int line)
{
    BLOCK_HDR *b;
    int prov;

    if (ptr == NULL)
        return t_malloc(num, file, line);
    if (num == 0) {
        t_free(ptr, file, line);
        return NULL;
    }
    if (should_fail(file, line, &prov)
            || (b = realloc((BLOCK_HDR *)ptr - 1, sizeof(*b) + num)) == NULL)
        return NULL;
    return b + 1;        /* the header (provider flag) moves with the block */
}

/* --- scenarios --- */

enum { PH_KEYGEN, PH_OPS };

typedef struct {
    const char *alg;
    int is_sig;
    int phase;
    EVP_PKEY *key;   /* PH_OPS: generated once, outside any injection */
    int encodable;   /* the baseline key-file round-trip succeeded */
    int binds_ctx;   /* the baseline signed under a context string */
} SCEN;

/* A DER PrivateKeyInfo of `k` decoded back into a key; 1 on success. */
static int keyfile_roundtrip(OSSL_LIB_CTX *ctx, const char *alg, EVP_PKEY *k)
{
    OSSL_ENCODER_CTX *e = NULL;
    OSSL_DECODER_CTX *d = NULL;
    unsigned char *der = NULL;
    const unsigned char *p;
    size_t derlen = 0;
    EVP_PKEY *out = NULL;
    int r = 0;

    e = OSSL_ENCODER_CTX_new_for_pkey(k, EVP_PKEY_KEYPAIR, "DER",
                                      "PrivateKeyInfo", PROPQ);
    if (e == NULL || OSSL_ENCODER_CTX_get_num_encoders(e) == 0
            || !OSSL_ENCODER_to_data(e, &der, &derlen))
        goto end;
    d = OSSL_DECODER_CTX_new_for_pkey(&out, "DER", "PrivateKeyInfo", alg,
                                      EVP_PKEY_KEYPAIR, ctx, PROPQ);
    p = der;
    r = d != NULL && OSSL_DECODER_from_data(d, &p, &derlen) && out != NULL;
end:
    EVP_PKEY_free(out);
    OSSL_DECODER_CTX_free(d);
    OSSL_ENCODER_CTX_free(e);
    OPENSSL_clear_free(der, derlen);
    return r;
}

/* The key-file step: probed in the baseline, required thereafter. */
static int keyfile_step(OSSL_LIB_CTX *ctx, SCEN *s, int baseline)
{
    if (baseline) {
        s->encodable = keyfile_roundtrip(ctx, s->alg, s->key);
        return 1;
    }
    return !s->encodable || keyfile_roundtrip(ctx, s->alg, s->key);
}

#ifdef OSSL_SIGNATURE_PARAM_CONTEXT_STRING
/*
 * The context-string path: sign under one (init param, then a copied
 * operation context, which duplicates the stored string), verify under it,
 * and never under another. A row that refuses context strings (hybrids with
 * a component that has none) is probed in the baseline and skipped after.
 * Returns a RUN_* value.
 */
static int ctx_step(OSSL_LIB_CTX *ctx, SCEN *s, EVP_PKEY *k, int baseline)
{
    static unsigned char cs_a[] = "alloc-fail-A", cs_b[] = "alloc-fail-B";
    OSSL_PARAM pa[2], pb[2];
    EVP_MD_CTX *m = NULL, *m2 = NULL;
    unsigned char *sig = NULL;
    size_t siglen = 0;
    int r = RUN_FAILED, signed_ok;

    if (!baseline && !s->binds_ctx)
        return RUN_OK;
    pa[0] = OSSL_PARAM_construct_octet_string(
                OSSL_SIGNATURE_PARAM_CONTEXT_STRING, cs_a, sizeof(cs_a) - 1);
    pa[1] = OSSL_PARAM_construct_end();
    pb[0] = OSSL_PARAM_construct_octet_string(
                OSSL_SIGNATURE_PARAM_CONTEXT_STRING, cs_b, sizeof(cs_b) - 1);
    pb[1] = OSSL_PARAM_construct_end();
    signed_ok = (m = EVP_MD_CTX_new()) != NULL
        && (m2 = EVP_MD_CTX_new()) != NULL
        && EVP_DigestSignInit_ex(m, NULL, NULL, ctx, PROPQ, k, pa) > 0
        && EVP_MD_CTX_copy_ex(m2, m) > 0
        && EVP_DigestSign(m2, NULL, &siglen, msg, sizeof(msg)) > 0
        && (sig = OPENSSL_malloc(siglen)) != NULL
        && EVP_DigestSign(m2, sig, &siglen, msg, sizeof(msg)) > 0;
    if (baseline) {
        s->binds_ctx = signed_ok;
        ERR_clear_error();
        if (!signed_ok) {               /* refused: fine, if refused cleanly */
            r = RUN_OK;
            goto end;
        }
    } else if (!signed_ok) {
        goto end;
    }
    /* Fail closed: never verify under another context string. */
    if (hybrid_test_verify(ctx, k, sig, siglen, msg, sizeof(msg), pb)) {
        r = RUN_UNSOUND;
        goto end;
    }
    if (hybrid_test_verify(ctx, k, sig, siglen, msg, sizeof(msg), pa))
        r = RUN_OK;
end:
    OPENSSL_free(sig);
    EVP_MD_CTX_free(m2);
    EVP_MD_CTX_free(m);
    return r;
}
#endif

static int run_sig(OSSL_LIB_CTX *ctx, SCEN *s, int baseline)
{
    EVP_PKEY *k = s->key, *pub = NULL;
    EVP_MD_CTX *m = NULL;
    unsigned char *sig = NULL;
    size_t siglen = 0;
    int r = RUN_FAILED;

    if ((m = EVP_MD_CTX_new()) == NULL
            || EVP_DigestSignInit_ex(m, NULL, NULL, ctx, PROPQ, k, NULL) <= 0
            || EVP_DigestSign(m, NULL, &siglen, msg, sizeof(msg)) <= 0
            || (sig = OPENSSL_malloc(siglen)) == NULL
            || EVP_DigestSign(m, sig, &siglen, msg, sizeof(msg)) <= 0)
        goto end;
    /* Fail closed: a corrupted signature must never verify, whatever failed. */
    sig[siglen - 1] ^= 0x01;
    if (hybrid_test_verify(ctx, k, sig, siglen, msg, sizeof(msg), NULL)) {
        r = RUN_UNSOUND;
        goto end;
    }
    sig[siglen - 1] ^= 0x01;
    if (!hybrid_test_verify(ctx, k, sig, siglen, msg, sizeof(msg), NULL)
            || (pub = hybrid_test_reimport(ctx, s->alg, k,
                                           EVP_PKEY_PUBLIC_KEY)) == NULL
            || !hybrid_test_verify(ctx, pub, sig, siglen, msg, sizeof(msg),
                                   NULL)
            || !keyfile_step(ctx, s, baseline))
        goto end;
#ifdef OSSL_SIGNATURE_PARAM_CONTEXT_STRING
    if ((r = ctx_step(ctx, s, k, baseline)) != RUN_OK)
        goto end;
#endif
    r = RUN_OK;
end:
    OPENSSL_free(sig);
    EVP_MD_CTX_free(m);
    EVP_PKEY_free(pub);
    return r;
}

static int run_kem(OSSL_LIB_CTX *ctx, SCEN *s, int baseline)
{
    EVP_PKEY *pub = NULL;
    EVP_PKEY_CTX *c = NULL;
    unsigned char *ct = NULL, *ss = NULL, *ss2 = NULL;
    size_t ctlen = 0, sslen = 0, ss2len;
    int r = RUN_FAILED;

    if ((pub = hybrid_test_reimport(ctx, s->alg, s->key,
                                    EVP_PKEY_PUBLIC_KEY)) == NULL
            || (c = EVP_PKEY_CTX_new_from_pkey(ctx, pub, PROPQ)) == NULL
            || EVP_PKEY_encapsulate_init(c, NULL) <= 0
            || EVP_PKEY_encapsulate(c, NULL, &ctlen, NULL, &sslen) <= 0
            || (ct = OPENSSL_malloc(ctlen)) == NULL
            || (ss = OPENSSL_malloc(sslen)) == NULL
            || (ss2 = OPENSSL_malloc(sslen)) == NULL
            || EVP_PKEY_encapsulate(c, ct, &ctlen, ss, &sslen) <= 0)
        goto end;
    /* Fail closed: a decaps that reports success yields the real secret. */
    ss2len = sslen;
    if (!hybrid_test_decaps(ctx, s->key, ct, ctlen, ss2, &ss2len))
        goto end;
    if (ss2len != sslen || CRYPTO_memcmp(ss, ss2, sslen) != 0) {
        r = RUN_UNSOUND;
        goto end;
    }
    if (!keyfile_step(ctx, s, baseline))
        goto end;
    r = RUN_OK;
end:
    if (ss != NULL)
        OPENSSL_clear_free(ss, sslen);
    if (ss2 != NULL)
        OPENSSL_clear_free(ss2, sslen);
    OPENSSL_free(ct);
    EVP_PKEY_CTX_free(c);
    EVP_PKEY_free(pub);
    return r;
}

static int run_scen(OSSL_LIB_CTX *ctx, SCEN *s, int baseline)
{
    EVP_PKEY *k;

    if (s->phase == PH_KEYGEN) {
        k = hybrid_test_keygen(ctx, s->alg);
        EVP_PKEY_free(k);
        return k != NULL ? RUN_OK : RUN_FAILED;
    }
    return s->is_sig ? run_sig(ctx, s, baseline) : run_kem(ctx, s, baseline);
}

/*
 * Arm the failure at provider allocation `at` (-1: none, and record each
 * allocation's call site), run, disarm. Returns the outcome; *n receives the
 * provider allocations reached, *leak the provider blocks left live.
 */
static int armed_run(OSSL_LIB_CTX *ctx, SCEN *s, int baseline, long at,
                     long *n, long *leak)
{
    long live = prov_live;
    int r;

    prov_allocs = 0;
    injected = 0;
    fail_at = at;
    recording = at < 0;
    r = run_scen(ctx, s, baseline);
    recording = 0;
    fail_at = -1;
    ERR_clear_error();
    *n = prov_allocs;
    *leak = prov_live - live;
    return r;
}

/*
 * The allocation indices to fail: every one under HYBRID_ALLOC_FAIL_EXHAUSTIVE,
 * otherwise up to SAMPLES_PER_SITE per call site, spread first..last. One site
 * is often reached many times with the same unwind (the decoder chain builds a
 * context in every candidate decoder and falls through to the next when one
 * fails), so sampling keeps the run short without losing a distinct path.
 */
#define SAMPLES_PER_SITE 4

static void select_indices(long n, int exhaustive)
{
    long i, j, c, occ[SAMPLES_PER_SITE], k, total;
    static long all[MAX_RECORDED];

    for (i = 0; i < n; i++)
        selected[i] = exhaustive;
    if (exhaustive)
        return;
    for (i = 0; i < n; i++) {
        if (rec_file[i] == NULL)        /* already grouped */
            continue;
        for (c = 0, j = i; j < n; j++)
            if (rec_file[j] != NULL && rec_line[j] == rec_line[i]
                    && strcmp(rec_file[j], rec_file[i]) == 0)
                all[c++] = j;
        total = c < SAMPLES_PER_SITE ? c : SAMPLES_PER_SITE;
        for (k = 0; k < total; k++)
            occ[k] = all[total == 1 ? 0 : k * (c - 1) / (total - 1)];
        for (k = 0; k < total; k++)
            selected[occ[k]] = 1;
        for (j = 0; j < c; j++)
            if (all[j] != i)
                rec_file[all[j]] = NULL;
        rec_file[i] = NULL;
    }
}

/* Inject the selected provider allocations of one phase; 1 if all clean. */
static int inject_phase(OSSL_LIB_CTX *ctx, SCEN *s, const char *what,
                        int exhaustive, long *ninj, long *nfail)
{
    long n, i, leak, reached;
    int r;

    /* Warm-up (also probes the key-file step): fetches and lazily-built
     * provider state persist in the libctx across runs, so the recorded run
     * that follows sees only the per-operation allocations. */
    if (armed_run(ctx, s, 1, -1, &n, &leak) != RUN_OK
            || armed_run(ctx, s, 0, -1, &n, &leak) != RUN_OK || leak != 0) {
        printf("FAIL: %s baseline (%ld provider blocks leaked)\n", what, leak);
        return 0;
    }
    if (n > MAX_RECORDED) {
        printf("FAIL: %s: %ld allocations exceed MAX_RECORDED\n", what, n);
        return 0;
    }
    select_indices(n, exhaustive);
    for (i = 0; i < n; i++) {
        if (!selected[i])
            continue;
        r = armed_run(ctx, s, 0, i, &reached, &leak);
        if (r == RUN_UNSOUND || leak != 0 || !injected) {
            printf("FAIL: %s allocation %ld/%ld (%s:%d): %s\n", what, i, n,
                   injected ? inj_file : "?", injected ? inj_line : 0,
                   r == RUN_UNSOUND ? "unsound success"
                   : leak != 0 ? "provider blocks leaked"
                   : "failure point not reached (nondeterministic)");
            if (leak != 0)
                printf("    %ld block(s) left live\n", leak);
            return 0;
        }
        ++*ninj;
        *nfail += r == RUN_FAILED;
    }
    /* The provider must be fully usable again after every injected failure. */
    if (armed_run(ctx, s, 0, -1, &n, &leak) != RUN_OK || leak != 0) {
        printf("FAIL: %s run after injection\n", what);
        return 0;
    }
    return 1;
}

static void check_alg(OSSL_LIB_CTX *ctx, const char *alg, int is_sig,
                      int exhaustive)
{
    SCEN s = { alg, is_sig, PH_KEYGEN, NULL, 0 };
    long ninj = 0, nfail = 0;
    int ok;

    printf("  %-34s ", alg);
    fflush(stdout);
    tests++;
    if ((s.key = hybrid_test_keygen(ctx, alg)) == NULL) {
        printf("SKIP (components unavailable)\n");
        skipped++; tests--;
        return;
    }
    ok = inject_phase(ctx, &s, "keygen", exhaustive, &ninj, &nfail);
    s.phase = PH_OPS;
    ok = ok && inject_phase(ctx, &s, is_sig ? "sign/verify" : "encaps/decaps",
                            exhaustive, &ninj, &nfail);
    EVP_PKEY_free(s.key);
    if (!ok) {
        failed++;
        return;
    }
    printf("ok (%ld injected, %ld failed closed%s)\n", ninj, nfail,
           s.encodable ? ", key file" : "");
    passed++;
}

/* --- provider load --- */

/*
 * Load the providers into a fresh libctx and generate one `alg` key. Only the
 * load is required to succeed (the key also needs its components); the keygen
 * drives the provider's lazily-built per-libctx state.
 */
static int load_providers(const char *mods, const char *alg)
{
    OSSL_LIB_CTX *ctx = OSSL_LIB_CTX_new();
    EVP_PKEY *k = NULL;
    int r = RUN_FAILED;

    if (ctx == NULL)
        goto end;
    if (mods != NULL)
        OSSL_PROVIDER_set_default_search_path(ctx, mods);
    if (hybrid_test_load(ctx, "default") == NULL
            || hybrid_test_load(ctx, "hybrid") == NULL)
        goto end;
    hybrid_test_load(ctx, "oqsprovider");
    k = hybrid_test_keygen(ctx, alg);
    r = RUN_OK;
end:
    EVP_PKEY_free(k);
    hybrid_test_libctx_free(ctx);
    ERR_clear_error();
    return r;
}

static void check_load(const char *mods, const char *alg)
{
    long n, i, live;

    printf("  %-34s ", "provider load + first fetch");
    fflush(stdout);
    tests++;
    live = prov_live;
    prov_allocs = 0;
    if (load_providers(mods, alg) != RUN_OK || prov_live != live) {
        printf("FAIL: baseline load\n");
        failed++;
        return;
    }
    n = prov_allocs;
    for (i = 0; i < n; i++) {
        live = prov_live;
        prov_allocs = 0;
        injected = 0;
        fail_at = i;
        load_providers(mods, alg);
        fail_at = -1;
        if (prov_live != live || !injected) {
            printf("FAIL: allocation %ld/%ld: %s\n", i, n,
                   prov_live != live ? "provider blocks leaked"
                   : "failure point not reached");
            failed++;
            return;
        }
    }
    printf("ok (%ld allocs)\n", n);
    passed++;
}

int main(void)
{
    OSSL_LIB_CTX *ctx;
    const char *mods = getenv("OPENSSL_MODULES");
    const char *ex = getenv("HYBRID_ALLOC_FAIL_EXHAUSTIVE");
    int exhaustive = ex != NULL && strcmp(ex, "1") == 0;
    size_t i;

    /* Must precede every libcrypto allocation. */
    if (!CRYPTO_set_mem_functions(t_malloc, t_realloc, t_free)) {
        fprintf(stderr, "CRYPTO_set_mem_functions refused (too late)\n");
        return 1;
    }
    if ((ctx = OSSL_LIB_CTX_new()) == NULL)
        return 1;
    if (mods != NULL)
        OSSL_PROVIDER_set_default_search_path(ctx, mods);
    if (hybrid_test_load(ctx, "default") == NULL
            || hybrid_test_load(ctx, "hybrid") == NULL) {
        fprintf(stderr, "failed to load default/hybrid providers\n");
        hybrid_test_libctx_free(ctx);
        return 1;
    }
    hybrid_test_load(ctx, "oqsprovider");
    ERR_clear_error();
    if (prov_live == 0) {
        /* Provider init allocates; zero means its sites carry no __FILE__
         * (OPENSSL_NO_FILENAMES), so nothing could be injected. */
        fprintf(stderr, "no provider allocation sites recognized\n");
        hybrid_test_libctx_free(ctx);
        return 1;
    }

    printf("allocation-failure injection (provider allocation sites)\n");
    printf("=========================================================\n");
    if (exhaustive)
        printf("  (exhaustive: every provider allocation is failed)\n");
    check_load(mods, hybrid_kem_table[0].hybrid_name);
    for (i = 0; i < HYBRID_SIG_ALG_COUNT; i++)
        check_alg(ctx, hybrid_sig_table[i].hybrid_name, 1, exhaustive);
    for (i = 0; i < HYBRID_KEM_ALG_COUNT; i++)
        check_alg(ctx, hybrid_kem_table[i].hybrid_name, 0, exhaustive);
#ifdef HYBRID_COMPOSITE
    for (i = 0; i < COMPOSITE_SIG_ALG_COUNT; i++)
        check_alg(ctx, composite_sig_table[i].name, 1, exhaustive);
    for (i = 0; i < COMPOSITE_KEM_ALG_COUNT; i++)
        check_alg(ctx, composite_kem_table[i].name, 0, exhaustive);
#endif

    printf("\nResults: %d/%d passed, %d failed, %d skipped\n",
           passed, tests, failed, skipped);
    hybrid_test_libctx_free(ctx);
    return failed == 0 ? 0 : 1;
}
